import type { Car } from "@/types/car";

// Deterministic, ever-increasing lock value so every photo across the whole
// mock catalog is a distinct (but stable) real car photo from LoremFlickr.
let lockCounter = 0;

/**
 * Real car photos tagged by body type, served through LoremFlickr
 * (https://loremflickr.com/1200/800/car,sedan) instead of generic
 * landscape/object placeholders.
 */
function images(tag: string, count: number, alt: string): Car["images"] {
  return Array.from({ length: count }, (_, i) => {
    lockCounter += 1;
    return {
      url: `https://loremflickr.com/1200/800/car,${tag}/all?lock=${lockCounter}`,
      alt: `${alt} - foto ${i + 1}`,
    };
  });
}

